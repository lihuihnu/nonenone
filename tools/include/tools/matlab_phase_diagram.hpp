/** @brief 生成 P-T 相区图的 MATLAB 代码。 */
inline void writePressureTemperatureMatlab(
    const std::filesystem::path &scriptPath,
    std::string_view csvFile,
    std::string_view figureTitle = "P-T phase map")
{
    std::ofstream out;
    detail::createMatlabFile(scriptPath, out);
    detail::writeMatlabPreamble(out, csvFile);
    out << "figure('Color','w'); hold on;\n";
    detail::writePhaseScatterLoop(out, "data.temperature_K", "data.pressure_bar");
    out << "nT = max(data.temperature_index)+1; nP = max(data.pressure_index)+1;\n"
        << "phaseCountGrid = nan(nP,nT);\n"
        << "for rr = 1:height(data)\n"
        << "    phaseCountGrid(data.pressure_index(rr)+1,data.temperature_index(rr)+1) = data.phase_count(rr);\n"
        << "end\n"
        << "Tgrid = sort(unique(data.temperature_K)); Pgrid = sort(unique(data.pressure_bar));\n"
        << "if any(phaseCountGrid(:) > 1)\n"
        << "    contour(Tgrid,Pgrid,phaseCountGrid,[1.5 2.5],'k-','LineWidth',1.1,'HandleVisibility','off');\n"
        << "end\n"
        << "xlabel('Temperature (K)'); ylabel('Pressure (bar)');\n"
        << "title('" << detail::matlabQuote(figureTitle) << "');\n"
        << "legend('Location','best'); grid on; box on;\n"
        << "set(gca,'Layer','top');\n";
}

