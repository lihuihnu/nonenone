inline std::string matlabQuote(std::string_view text)
{
    std::string result;
    result.reserve(text.size() + 4);
    for (const char ch : text)
    {
        result.push_back(ch);
        if (ch == '\'')
            result.push_back('\'');
    }
    return result;
}

inline void writeMatlabPreamble(std::ostream &out, std::string_view csvFile)
{
    out << "% Auto-generated by MPMC_SCW tools.\n"
        << "% phase_code: 0=failed, 1=O, 2=G, 3=O+G, 4=W, 5=O+W, 6=G+W, 7=O+G+W.\n"
        << "clear; clc;\n"
        << "data = readtable('" << matlabQuote(csvFile) << "');\n"
        << "phaseNames = {'failed','O','G','O+G','W','O+W','G+W','O+G+W'};\n"
        << "phaseColors = lines(8);\n"
        << "if any(ismember(data.Properties.VariableNames, {'phase_code'}))\n"
        << "    valid = data.phase_code > 0;\n"
        << "    if any(~valid)\n"
        << "        fprintf('Warning: %d phase-diagram samples did not converge.\\n', sum(~valid));\n"
        << "    end\n"
        << "else\n"
        << "    valid = true(height(data),1);\n"
        << "end\n";
}

inline void writePhaseScatterLoop(
    std::ostream &out,
    std::string_view xExpression,
    std::string_view yExpression)
{
    out << "codes = unique(data.phase_code(valid));\n"
        << "for ii = 1:numel(codes)\n"
        << "    code = codes(ii);\n"
        << "    mask = data.phase_code == code;\n"
        << "    scatter(" << xExpression << "(mask), " << yExpression
        << "(mask), 20, phaseColors(code+1,:), 'filled', ...\n"
        << "        'DisplayName', phaseNames{code+1});\n"
        << "end\n";
}

inline void createMatlabFile(const std::filesystem::path &path, std::ofstream &out)
{
    if (path.has_parent_path())
        std::filesystem::create_directories(path.parent_path());
    out.open(path);
    if (!out)
        throw std::runtime_error("Cannot create MATLAB phase-diagram script: " + path.string());
}

